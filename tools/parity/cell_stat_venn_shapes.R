#!/usr/bin/env Rscript
# Generate src/scp/pl/_venn_shapes.py from ggVennDiagram's shape table.
#
#   Rscript tools/parity/cell_stat_venn_shapes.R <ggVennDiagram_checkout> [out.py]
#
# SCP's venn code (SCP-plot.R:4981) was written against the sf-based
# ggVennDiagram 1.2.x API: process_data() there picks, for n sets, the FIRST
# shape_id listed for that n in the package's internal `shapes` table. This
# reads that table from a checkout of tag V1.2.2 (R/sysdata.rda; loading it
# needs no sf, the geometries are plain matrices underneath) and writes the
# chosen shape per set count -- its set outlines and set-label anchors -- into
# a Python module.
#
# Outlines are quantised to uint16 over each shape's bounding box and stored
# base64-encoded: 1/65535 of the extent is far below anything visible, and it
# keeps the module to a few tens of kilobytes.
#
# ggVennDiagram is GPL-3 (Chun-Hui Gao); the shapes come originally from the
# `venn` package (Adrian Dusa) and VennDiagram (Hanbo Chen). The generated
# module carries that attribution.

suppressPackageStartupMessages(library(jsonlite))
args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 1) stop("usage: cell_stat_venn_shapes.R <ggVennDiagram_checkout> [out.py]")
src <- args[[1]]
out <- if (length(args) >= 2) args[[2]] else "src/scp/pl/_venn_shapes.py"

e <- new.env()
load(file.path(src, "R", "sysdata.rda"), envir = e)
s <- e$shapes
xy <- unclass(s$xy)

b64 <- function(v) {
  con <- rawConnection(raw(0), "wb")
  writeBin(as.integer(v), con, size = 2, endian = "little")
  r <- rawConnectionValue(con)
  close(con)
  gsub("[\r\n]", "", base64_enc(r))
}
wrap <- function(x, width = 72) {
  starts <- seq(1, nchar(x), by = width)
  substring(x, starts, pmin(starts + width - 1, nchar(x)))
}
fmt <- function(x) trimws(formatC(x, digits = 10, format = "g"))

lines <- c(
  '"""Venn set outlines, one shape per set count (1-7).',
  "",
  "Generated by ``tools/parity/cell_stat_venn_shapes.R`` from ggVennDiagram",
  "1.2.2's internal shape table -- the version whose API SCP's ``StatPlot``",
  "was written against -- taking, as its ``process_data()`` does, the first",
  "shape listed for each set count. Do not edit by hand.",
  "",
  "ggVennDiagram (GPL-3) is by Chun-Hui Gao, https://github.com/gaospecial/ggVennDiagram;",
  "the outlines derive from the ``venn`` package (Adrian Dusa) and, for the",
  "four-set ellipses, VennDiagram (Hanbo Chen).",
  "",
  "Each outline is a closed ring of points quantised to uint16 over the shape's",
  "bounding box ``(xmin, xmax, ymin, ymax)``, little-endian, x then y",
  "interleaved, base64-encoded.",
  '"""',
  "",
  "SHAPES: dict[int, dict] = {"
)
for (n in 1:7) {
  ids <- unique(s$shape_id[s$nsets == n])
  sid <- ids[[1]]
  ie <- which(s$shape_id == sid & s$component == "setEdge")
  il <- which(s$shape_id == sid & s$component == "setLabel")
  ie <- ie[order(as.integer(s$id[ie]))]
  il <- il[order(as.integer(s$id[il]))]
  edges <- lapply(xy[ie], function(g) matrix(as.numeric(unclass(g)), ncol = 2))
  allx <- unlist(lapply(edges, function(m) m[, 1])); ally <- unlist(lapply(edges, function(m) m[, 2]))
  bb <- c(min(allx), max(allx), min(ally), max(ally))
  lines <- c(lines, sprintf("    %d: {", n), sprintf('        "shape_id": "%s",', sid),
             sprintf('        "type": "%s",', s$type[ie[1]]),
             sprintf("        \"bbox\": (%s),", paste(fmt(bb), collapse = ", ")),
             '        "edges": (')
  for (m in edges) {
    qx <- round((m[, 1] - bb[1]) / (bb[2] - bb[1]) * 65535)
    qy <- round((m[, 2] - bb[3]) / (bb[4] - bb[3]) * 65535)
    enc <- b64(as.vector(rbind(qx, qy)))
    lines <- c(lines, "            (", paste0('                "', wrap(enc), '"'), "            ),")
  }
  labs <- vapply(xy[il], function(p) {
    p <- as.numeric(unclass(p))
    sprintf("(%s, %s)", fmt(p[1]), fmt(p[2]))
  }, character(1))
  lines <- c(lines, "        ),", sprintf('        "labels": (%s,),', paste(labs, collapse = ", ")), "    },")
}
lines <- c(lines, "}")
writeLines(lines, out)
message("wrote ", out)
