def test_dynamic_heatmap_r_matrix_is_joint_zscore_of_lib_normalised_cells(inputs, dynheat):
    """R's matrix is per cell, lib-normalised, and z-scored once across ALL lineages.

    Reproduced here with the package's own ``matrix_process``: this is the
    target for the fix below.
    """
    M, order, _f = dynheat
    feats = list(M.index)
    tab = inputs.set_index(inputs["cell"].astype(str))
    lib = tab["libsize"].to_numpy(dtype=float)
    cells = order["cell"].astype(str).to_numpy()
    raw = tab.loc[cells, [f"gene_{g}" for g in feats]].to_numpy(dtype=float).T
    raw = raw / tab.loc[cells, "libsize"].to_numpy(dtype=float) * np.median(lib)
    np.testing.assert_allclose(scp.matrix_process(raw, "zscore"), M.to_numpy(), atol=1e-6)


