def _match_by_position(r: pd.DataFrame, coll) -> tuple[float, list[str], list[str]]:
    r = r.dropna(subset=["x", "y"]).reset_index(drop=True)
    pos = coll.get_offsets()
    py = _hexes(coll.get_facecolors())
    worst, rc, pc = 0.0, [], []
    for (x, y), c in zip(pos, py, strict=True):
        d = np.hypot(r.x - x, r.y - y)
        j = int(np.argmin(d))
        if d[j] > 1e-5:
            continue  # censored on the R side (see the next test)
        worst = max(worst, float(d[j]))
        rc.append(str(r.colour[j]).upper())
        pc.append(c)
    return worst, rc, pc


def test_projection_reference_and_query_colours_match_r(projection):
    ref, qry, R = projection
    ax = scp.pl.projection_plot(qry, ref, query_group="SubCellType", ref_group="CellType")
    cols = [c for c in ax.collections if isinstance(c, PathCollection)]
    worst, rc, pc = _match_by_position(R[R.layer == 1], cols[0])
    assert len(rc) == ref.n_obs and worst < 1e-5 and rc == pc
    worst, rc, pc = _match_by_position(R[R.layer == 3], cols[2])
    assert len(rc) == int(R[R.layer == 3][["x", "y"]].notna().all(axis=1).sum()) and rc == pc


def test_projection_keeps_query_cells_outside_the_reference_range(projection):
    """R bug, deliberately not reproduced.

    ProjectionPlot computes the union of both ranges but applies it only to the
    throwaway query plot; the composite inherits CellDimPlot's reference-range
    scale limits, so query cells beyond it are censored to NA and silently
    dropped.  Python keeps them on shared limits, which is what R evidently
    intended.
    """
    ref, qry, R = projection
    rq = R[R.layer == 3]
    assert rq.x.isna().sum() > 0
    ax = scp.pl.projection_plot(qry, ref, query_group="SubCellType", ref_group="CellType")
    cols = [c for c in ax.collections if isinstance(c, PathCollection)]
    assert cols[2].get_offsets().shape[0] == qry.n_obs
    assert ax.get_xlim()[1] >= qry.obsm["X_umap"][:, 0].max()
