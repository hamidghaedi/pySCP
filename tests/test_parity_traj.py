def _r_parts(name):
    R = _csv(f"{name}_layers.csv")
    seg = R[R.geom.str.contains("Segment")]
    edges = seg[seg.colour == "grey40"]
    trans = seg[seg.colour == "black"]
    pts = R[R.geom.str.contains("Point")]
    first, last = sorted(pts.layer.unique())[0], sorted(pts.layer.unique())[-1]
    return edges, trans, pts[pts.layer == first], pts[pts.layer == last]


def _py_parts(ax):
    lcs = [c for c in ax.collections if isinstance(c, LineCollection)]
    edges = (np.array([[s[0][0], s[0][1], s[1][0], s[1][1]] for s in lcs[0].get_segments()])
             if lcs else np.zeros((0, 4)))
    widths = np.asarray(lcs[0].get_linewidths()) if lcs else np.zeros(0)
    arrows = [a for a in ax.texts if isinstance(a, Annotation)]
    trans = (np.array([[a.xyann[0], a.xyann[1], a.xy[0], a.xy[1]] for a in arrows])
             if arrows else np.zeros((0, 4)))
    pts = [c for c in ax.collections if isinstance(c, PathCollection)]
    return edges, widths, trans, arrows, pts


def _match_rows(R: np.ndarray, P: np.ndarray) -> np.ndarray:
    """Order-free row matching; returns the max abs deviation per R row."""
    assert R.shape == P.shape, (R.shape, P.shape)
    out = []
    taken: set[int] = set()
    for r in R:
        d = np.abs(P - r).max(axis=1)
        j = int(np.argmin(d))
        assert j not in taken
        taken.add(j)
        out.append(d[j])
    return np.asarray(out)


