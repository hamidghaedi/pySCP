@pytest.mark.parametrize("case", ["transition", "transition_offset"])
def test_paga_net_transition_pairs_and_direction_match_r(r_adata, case):
    """Net flow, the pair kept and the arrow direction agree with R.

    Midpoints and unit directions are invariant to the (equal) start/end
    shortening, so they pin the net-transition logic independently of the
    global_size mismatch below.  Offset moves the midpoint, so only the
    unshifted case compares midpoints.
    """
    _e, trans, *_ = _r_parts(f"paga_{case}")
    _e2, _w, t, *_ = _py_parts(_paga(r_adata, case))
    R = trans[["x", "y", "xend", "yend"]].to_numpy()
    assert R.shape == t.shape

    def unit(a):
        d = a[:, 2:] - a[:, :2]
        return d / np.linalg.norm(d, axis=1, keepdims=True)

    if case == "transition":
        mid_r, mid_p = (R[:, :2] + R[:, 2:]) / 2, (t[:, :2] + t[:, 2:]) / 2
        assert _match_rows(np.c_[mid_r, unit(R)], np.c_[mid_p, unit(t)]).max() < 1e-6
    else:
        assert _match_rows(unit(R), unit(t)).max() < 1e-6


